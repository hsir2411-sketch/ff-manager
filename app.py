@app.route("/dashboard")
@login_required
def dashboard():
    conn = db()
    if g.user["role"] == "admin":
        players = conn.execute("SELECT id,display_name,username FROM users WHERE role='player' ORDER BY display_name").fetchall()
        total_matches = conn.execute("SELECT COUNT(*) FROM matches").fetchone()[0]
        task_total = conn.execute("SELECT COUNT(*) FROM training_tasks").fetchone()[0]
        task_done = conn.execute("SELECT COUNT(*) FROM training_tasks WHERE completed=1").fetchone()[0]
        recent = conn.execute("""SELECT m.*,u.display_name FROM matches m JOIN users u ON u.id=m.player_id
                                 ORDER BY m.played_on DESC,m.id DESC LIMIT 8""").fetchall()
        ranking = conn.execute("""SELECT u.id,u.display_name,
              COUNT(m.id) games, COALESCE(SUM(m.kills),0) kills,
              COALESCE(ROUND(AVG(m.damage)),0) avg_damage,
              COALESCE(ROUND(AVG(CASE WHEN m.mode='BR' THEN m.placement END),1),0) avg_placement
              FROM users u LEFT JOIN matches m ON m.player_id=u.id
              WHERE u.role='player' GROUP BY u.id ORDER BY kills DESC, avg_damage DESC""").fetchall()
        return render_template("admin_dashboard.html", players=players, total_matches=total_matches,
                               task_total=task_total, task_done=task_done, recent=recent, ranking=ranking)
    matches = conn.execute("SELECT * FROM matches WHERE player_id=%s ORDER BY played_on DESC,id DESC LIMIT 8",
                           (g.user["id"],)).fetchall()
    tasks = conn.execute("SELECT * FROM training_tasks WHERE assigned_to=%s ORDER BY completed,due_date LIMIT 8",
                         (g.user["id"],)).fetchall()
    stats = conn.execute("""SELECT COUNT(*) games,COALESCE(SUM(kills),0) kills,
                    COALESCE(ROUND(AVG(damage)),0) avg_damage
                    FROM matches WHERE player_id=%s""",(g.user["id"],)).fetchone()
    return render_template("player_dashboard.html", matches=matches, tasks=tasks, stats=stats)

@app.route("/players", methods=["GET","POST"])
@admin_required
def players():
    conn = db()
    if request.method == "POST":
        username = request.form.get("username","").strip().lower()
        display_name = request.form.get("display_name","").strip()
        password = request.form.get("password","")
        if not username or not display_name or len(password) < 8:
            flash("Fill all fields; password must be at least 8 characters.", "error")
        else:
            try:
                existing = conn.execute("SELECT id FROM users WHERE username = %s COLLATE NOCASE", (username,)).fetchone()
                if existing:
                    flash("That username already exists. Use a different username.", "error")
                    return redirect(url_for("players"))
                conn.execute("INSERT INTO users(username,password_hash,role,display_name) VALUES(%s,%s,%s,%s)",
                             (username,generate_password_hash(password),"player",display_name))
                conn.commit()
                flash("Player account created.", "success")
                return redirect(url_for("players"))
            except psycopg.IntegrityError:
                flash("That username already exists.", "error")
    rows = conn.execute("SELECT id,username,display_name,created_at FROM users WHERE role='player' ORDER BY display_name").fetchall()
    return render_template("players.html", players=rows)

