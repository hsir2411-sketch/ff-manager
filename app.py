def db():
    if not DATABASE_URL:
        raise RuntimeError("DATABASE_URL is not configured. Set it in your environment.")
    if "db" not in g:
        g.db = psycopg.connect(DATABASE_URL, row_factory=dict_row, sslmode="require")
    return g.db

@app.teardown_appcontext
def close_db(exc):
    conn = g.pop("db", None)
    if conn is not None:
        conn.close()

def init_db():
    """Create PostgreSQL tables if they do not exist."""
    if not DATABASE_URL:
        return
    with psycopg.connect(DATABASE_URL, sslmode="require", row_factory=dict_row) as conn:
        conn.execute("""
        CREATE TABLE IF NOT EXISTS users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          username TEXT UNIQUE NOT NULL, password_hash TEXT NOT NULL,
          role TEXT NOT NULL CHECK(role IN ('admin','player')),
          display_name TEXT NOT NULL, photo TEXT NOT NULL DEFAULT '',
          ign TEXT NOT NULL DEFAULT '', free_fire_uid TEXT NOT NULL DEFAULT '',
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS matches (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          player_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          mode TEXT NOT NULL CHECK(mode IN ('BR','CS')), played_on DATE NOT NULL,
          opponent_or_map TEXT DEFAULT '', kills INTEGER NOT NULL DEFAULT 0,
          damage INTEGER NOT NULL DEFAULT 0, placement INTEGER DEFAULT NULL,
          rounds_won INTEGER NOT NULL DEFAULT 0, rounds_lost INTEGER NOT NULL DEFAULT 0,
          notes TEXT DEFAULT '', created_by BIGINT REFERENCES users(id),
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS training_tasks (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          title TEXT NOT NULL, category TEXT NOT NULL DEFAULT 'General',
          details TEXT DEFAULT '', due_date DATE NOT NULL,
          assigned_to BIGINT REFERENCES users(id) ON DELETE CASCADE,
          completed INTEGER NOT NULL DEFAULT 0, coach_note TEXT DEFAULT '',
          created_by BIGINT REFERENCES users(id),
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        CREATE TABLE IF NOT EXISTS reviews (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          player_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          review_date DATE NOT NULL, strength TEXT DEFAULT '',
          improvement_area TEXT DEFAULT '', next_goal TEXT DEFAULT '',
          coach_id BIGINT REFERENCES users(id),
          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
        """)
        count = conn.execute("SELECT COUNT(*) AS count FROM users").fetchone()["count"]
        if count == 0 and os.environ.get("SEED_DEMO_USERS", "1") == "1":
            conn.execute("INSERT INTO users(username,password_hash,role,display_name) VALUES(%s,%s,%s,%s)",
                         ("admin", generate_password_hash("Admin123!"), "admin", "Team Admin"))
            conn.execute("INSERT INTO users(username,password_hash,role,display_name) VALUES(%s,%s,%s,%s)",
                         ("player1", generate_password_hash("Player123!"), "player", "Player One"))

@app.before_request
def load_user():
    g.user = None
    if session.get("user_id"):
        g.user = db().execute("SELECT id,username,role,display_name FROM users WHERE id=%s",
                              (session["user_id"],)).fetchone()

def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not g.user:
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped

def admin_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not g.user:
            return redirect(url_for("login"))
        if g.user["role"] != "admin":
            abort(403)
        return view(*args, **kwargs)
    return wrapped

