@app.route("/matches", methods=["GET","POST"])
@login_required
def matches():
    conn = db()
    if request.method == "POST":
        player_id = g.user["id"] if g.user["role"] == "player" else request.form.get("player_id", type=int)
        if not player_id:
            flash("Choose a player.", "error")
            return redirect(url_for("matches"))
        mode = request.form.get("mode","BR")
        played_on = request.form.get("played_on") or date.today().isoformat()
        kills = max(0, request.form.get("kills",0,type=int))
        damage = max(0, request.form.get("damage",0,type=int))
        placement = request.form.get("placement",type=int)
        rounds_won = max(0, request.form.get("rounds_won",0,type=int))
        rounds_lost = max(0, request.form.get("rounds_lost",0,type=int))
        map_name = request.form.get("opponent_or_map","").strip()
        notes = request.form.get("notes","").strip()
        if mode not in ("BR","CS"):
            abort(400)
        if g.user["role"] == "player" and player_id != g.user["id"]:
            abort(403)
        conn.execute("""INSERT INTO matches(player_id,mode,played_on,opponent_or_map,kills,damage,placement,
                        rounds_won,rounds_lost,notes,created_by) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)""",
                     (player_id,mode,played_on,map_name,kills,damage,placement,rounds_won,rounds_lost,notes,g.user["id"]))
        conn.commit()
        flash("Match record saved.", "success")
        return redirect(url_for("matches"))
    if g.user["role"] == "admin":
        rows = conn.execute("""SELECT m.*,u.display_name FROM matches m JOIN users u ON u.id=m.player_id
                               ORDER BY m.played_on DESC,m.id DESC""").fetchall()
        player_rows = conn.execute("SELECT id,display_name FROM users WHERE role='player' ORDER BY display_name").fetchall()
    else:
        rows = conn.execute("SELECT *,%s AS display_name FROM matches WHERE player_id=%s ORDER BY played_on DESC,id DESC",
                            (g.user["display_name"],g.user["id"])).fetchall()
        player_rows = []
    return render_template("matches.html", matches=rows, players=player_rows, today=date.today().isoformat())

